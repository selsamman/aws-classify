// Build the code blocks from the guide, in an isolated consumer workspace.
const assert = require('node:assert/strict');
const {execFileSync} = require('node:child_process');
const {mkdirSync, readFileSync, writeFileSync, readdirSync, existsSync} = require('node:fs');
const {resolve, join} = require('node:path');
const root = resolve(__dirname, '..');
const directory = resolve(process.argv[2] || join(root, '.test-results/static-pages-recipe', Date.now().toString(36)));
const guide = readFileSync(join(root, 'usersguide/content/guides/static-pages.md'), 'utf8');
const blocks = [...guide.matchAll(/```[^\n]*\n([\s\S]*?)\n```/g)].map(match => match[1]);
const block = start => {const result = blocks.find(code => code.startsWith(start)); assert.ok(result, start); return result;};
const write = (file, content) => {mkdirSync(resolve(directory, file, '..'), {recursive: true}); writeFileSync(join(directory, file), content + '\n');};
const run = args => execFileSync('npm', args, {cwd: directory, stdio: 'inherit', env: {...process.env, npm_config_cache: process.env.npm_config_cache || join(root, '.test-results/npm-cache')}});
const [major, minor] = process.versions.node.split('.').map(Number);
assert.ok(major > 22 || (major === 22 && minor >= 12), 'Use Node 22.12 or later for the Vite/Minista recipe');
assert.equal(existsSync(directory), false, 'Use a fresh fixture directory');
write('package.json', JSON.stringify({name: 'static-pages-recipe', private: true, workspaces: ['web', 'public-site'], awsClassify: {spaDirectory: 'app'}, scripts: {'build:site': 'npm run build --workspace public-site && npm run build --workspace web && node scripts/assemble-site.mjs'}}));
run(['create', 'vite@latest', 'web', '--', '--template', 'react-ts', '--no-interactive']);
write('web/vite.config.ts', block("import {readFileSync}"));
write('public-site/package.json', block('{\n  "name": "public-site"'));
write('public-site/vite.config.ts', block("import {defineConfig, pluginSsg}"));
write('public-site/tsconfig.json', block('{\n  "compilerOptions"'));
write('public-site/src/layouts/index.tsx', block("import type {LayoutProps}"));
write('public-site/src/pages/index.tsx', block("import {Head}"));
write('public-site/src/pages/about.tsx', blocks.find(code => code.startsWith("import {Head}") && code.includes('function About')));
write('scripts/assemble-site.mjs', block('import {cpSync'));
run(['install', '--save-dev', 'minista@^5', 'vite@^8.1', 'typescript', '@types/react', '@types/react-dom', '--workspace', 'public-site']);
run(['install', 'react@^19', 'react-dom@^19', '--workspace', 'public-site']);
run(['install']);
run(['run', 'build:site']);
run(['exec', '--workspace', 'public-site', '--', 'tsc', '--noEmit']);
const html = file => readFileSync(join(directory, 'site-dist', file), 'utf8');
for (const [file, title, description, heading] of [['index.html', 'My application', 'Welcome to my application.', 'Welcome'], ['about.html', 'About', 'About our application.', 'About']]) {
    const page = html(file);
    assert.match(page, /<!doctype html>/i); assert.match(page, /<html lang="en">/);
    const head = page.match(/<head>([\s\S]*?)<\/head>/)[1];
    assert.ok(head.includes(`<title>${title}</title>`));
    assert.ok(head.includes(`content="${description}"`));
    assert.match(head, /name="viewport"/);
    assert.ok(page.includes(`<h1>${heading}</h1>`));
    for (const link of ['/', '/about.html', '/app']) assert.ok(page.includes(`href="${link}"`));
    assert.match(page, /<footer>My application<\/footer>/);
    assert.equal((page.match(/<title>/g) || []).length, 1);
}
const spa = html('app/index.html');
const assets = [...spa.matchAll(/(?:src|href)="(\/app\/assets\/[^\"]+)"/g)].map(match => match[1]);
assert.ok(assets.some(asset => asset.endsWith('.js'))); assert.ok(assets.some(asset => asset.endsWith('.css')));
for (const asset of assets) assert.ok(existsSync(join(directory, 'site-dist', asset)));
assert.equal(spa.includes('src="/assets/'), false);
const files = readdirSync(join(directory, 'site-dist'), {recursive: true});
write('verification.json', JSON.stringify({result: 'passed', node: process.version, checks: ['Vite React TypeScript build', 'Minista build and typecheck', 'complete public documents', 'shared layout and navigation', 'page-specific head metadata', 'SPA asset base URLs', 'combined publication output'], files}, null, 2));
console.log(`Recipe verified: ${directory}`);
